def plot_caption_pipeline_row(
    row: Recording,
    save_path: str | None = None,
    *,
    example: str = "auto",
    channel_names: list[str] | tuple[str, ...] | None = None,
    caption_types: tuple[str, ...] = DEFAULT_PIPELINE_CAPTION_TYPES,
    max_caption_cards: int = 6,
    include_statistical: bool = False,
    title: str | None = None,
) -> plt.Figure | None:
    """Render a paper-style captioning pipeline figure for one annotated row."""
    selected_names = _resolve_pipeline_channels(row, example=example, channel_names=channel_names)
    selected_indices = [row.channel_names.index(name) for name in selected_names]
    selected_set = set(selected_indices)
    annotations = _select_pipeline_annotations(
        row,
        selected_set,
        example=example,
        caption_types=caption_types,
        include_statistical=include_statistical,
        max_cards=max_caption_cards,
    )

    base_height = max(8.2, 1.34 * len(selected_indices) + 2.9)
    fig = plt.figure(
        figsize=(18.0, base_height + _estimate_caption_panel_extra_height(annotations)),
        facecolor="white",
    )
    grid = fig.add_gridspec(
        1,
        2,
        width_ratios=[1.18, 1.10],
        left=0.045,
        right=0.975,
        top=0.925,
        bottom=0.062,
        wspace=0.028,
    )
    ax_signal = fig.add_subplot(grid[0, 0])
    ax_cards = fig.add_subplot(grid[0, 1])
    ax_cards.axis("off")

    _draw_pipeline_signal_panel(ax_signal, row, selected_indices, annotations)
    _draw_pipeline_caption_panel(ax_cards, annotations)

    figure_title = title or f"Captioning pipeline example | {row.date}"
    fig.text(0.045, 0.980, figure_title, ha="left", va="top", fontsize=24, weight="bold")
    fig.text(
        0.045,
        0.960,
        "Highlighted signal regions are paired with the natural-language annotations generated by the extractor and synthesizer stages.",
        ha="left",
        va="top",
        fontsize=13.8,
        color="#4b5563",
    )

    if save_path:
        save_target = Path(save_path)
        save_target.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(save_target, dpi=220, bbox_inches="tight", facecolor="white")
        plt.close(fig)
        return None

    plt.show()
    return fig


def _resolve_pipeline_channels(
    row: Recording,
    *,
    example: str,
    channel_names: list[str] | tuple[str, ...] | None,
) -> list[str]:
    aliases = _channel_aliases_for_row(row)
    if channel_names:
        resolved = [
            aliases.get(name, name)
            for name in channel_names
            if aliases.get(name, name) in row.channel_names
        ]
        if resolved:
            return resolved

    example = example.lower()
    if _is_wesad_row(row):
        candidates = _wesad_default_channel_candidates(row, example=example)
    else:
        if example == "auto":
            labels = {str(annotation.label or "") for annotation in row.annotations}
            if {"sleep_asleep", "sleep_inbed", "in_bed_not_sleeping"} & labels:
                example = "sleep"
            else:
                example = "walking"

        if example == "sleep":
            candidates = ("WHR", "WDist", "WSteps", "SleepAsleep", "SleepInBed")
        else:
            workout_alias = _first_present_workout_alias(row) or "Walk"
            candidates = ("WHR", "WSteps", "WDist", "WEnergy", workout_alias)

    resolved = [aliases[name] for name in candidates if aliases[name] in row.channel_names]
    if _is_wesad_row(row):
        # Always include all WESAD binary state channels so semantic/cross-channel
        # context is visible regardless of the selected physiological preset.
        for state_alias in ("Baseline", "Stress", "Amusement", "Meditation"):
            state_name = aliases.get(state_alias, state_alias)
            if state_name in row.channel_names and state_name not in resolved:
                resolved.append(state_name)
    if resolved:
        return resolved

    active = [signal.name for signal in row.iter_channels() if signal.has_any_data]
    return active[: min(5, len(active))] or list(row.channel_names[: min(5, len(row.channel_names))])


def _channel_aliases_for_row(row: Recording) -> dict[str, str]:
    if _is_wesad_row(row):
        return WESAD_CHANNEL_ALIASES
    return MHC_CHANNEL_ALIASES


def _is_wesad_row(row: Recording) -> bool:
    return bool(row.channel_names) and str(row.channel_names[0]).startswith("wesad:")


def _wesad_default_channel_candidates(row: Recording, *, example: str) -> tuple[str, ...]:
    if example == "sleep":
        return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Meditation")
    if example == "walking":
        return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Stress")
    if example == "auto":
        labels = {str(annotation.label or "") for annotation in row.annotations}
        if "calm_meditation" in labels or "wesad:label:meditation" in labels:
            return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Meditation")
        if "amusement_activation" in labels or "wesad:label:amusement" in labels:
            return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Amusement")
        if "stress_response" in labels or "wesad:label:stress" in labels:
            return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Stress")
        return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Baseline")
    return ("WristHR", "WristEDA", "WristBVP", "ChestResp", "Stress")


def _first_present_workout_alias(row: Recording) -> str | None:
    workout_aliases = ("Walk", "Run", "Cycle", "Elliptical", "HIIT", "OtherWorkout")
    for alias in workout_aliases:
        name = MHC_CHANNEL_ALIASES[alias]
        if name not in row.channel_names:
            continue
        values = np.asarray(row.values[row.channel_names.index(name)], dtype=float)
        if np.any(np.isfinite(values) & (values > 0)):
            return alias
    return None


def _select_pipeline_annotations(
    row: Recording,
    selected_indices: set[int],
    *,
    example: str,
    caption_types: tuple[str, ...],
    include_statistical: bool,
    max_cards: int,
) -> list[Annotation]:
    allowed_types = set(caption_types)
    # WESAD figures should always show statistical context in the card panel.
    if include_statistical or _is_wesad_row(row):
        allowed_types.add("statistical")

    candidates = [
        annotation
        for annotation in row.annotations
        if annotation.text
        and annotation.caption_type in allowed_types
        and (not annotation.channel_idxs or selected_indices.intersection(annotation.channel_idxs))
        and _annotation_has_selected_semantic_source(row, annotation, selected_indices)
        and _annotation_matches_pipeline_example(row, annotation, example)
    ]
    if _is_wesad_row(row) and "cross_channel" in allowed_types:
        # Ensure WESAD cross-channel events are retained even if channel/example
        # filters would otherwise remove some of them.
        wesad_cross_channel = [
            annotation
            for annotation in row.annotations
            if annotation.text and annotation.caption_type == "cross_channel"
        ]
        wesad_cross_channel.sort(key=_annotation_sort_key)
        for annotation in wesad_cross_channel:
            if annotation not in candidates:
                candidates.append(annotation)
    candidates.sort(key=_annotation_sort_key)

    return _stage_balanced_annotations(candidates, max_per_stage=max_cards)


def _stage_balanced_annotations(annotations: list[Annotation], *, max_per_stage: int) -> list[Annotation]:
    selected: list[Annotation] = []

    for caption_type in PIPELINE_CARD_STAGE_ORDER:
        stage_annotations = [annotation for annotation in annotations if annotation.caption_type == caption_type]
        if caption_type == "structural":
            selected.extend(_select_structural_annotations(stage_annotations, max_items=max_per_stage))
        elif caption_type == "cross_channel":
            # Keep all cross-channel events so none are hidden from the box.
            selected.extend(stage_annotations)
        else:
            selected.extend(stage_annotations[:max_per_stage])

    return selected


def _select_structural_annotations(annotations: list[Annotation], *, max_items: int) -> list[Annotation]:
    if len(annotations) <= max_items:
        return annotations

    selected: list[Annotation] = []
    selected_ids: set[int] = set()
    for predicate in (_is_spike_caption, _is_trend_caption):
        for annotation in annotations:
            if id(annotation) in selected_ids or not predicate(annotation):
                continue
            selected.append(annotation)
            selected_ids.add(id(annotation))
            break

    for annotation in annotations:
        if id(annotation) in selected_ids:
            continue
        selected.append(annotation)
        if len(selected) >= max_items:
            break
    return selected


def _annotation_matches_pipeline_example(row: Recording, annotation: Annotation, example: str) -> bool:
    example = example.lower()
    label = str(annotation.label or "")
    if example == "auto":
        return True
    if example == "sleep":
        if label.startswith("sleep_") or label == "in_bed_not_sleeping":
            return True
        return any(row.channel_names[idx].startswith("sleep:") for idx in annotation.channel_idxs)
    if example == "walking":
        if label.startswith("sleep_") or label == "in_bed_not_sleeping":
            return False
        if annotation.caption_type == "semantic":
            return any(
                idx < len(row.channel_names) and row.channel_names[idx].startswith("workout:")
                for idx in annotation.channel_idxs
            )
        return True
    return True


def _annotation_has_selected_semantic_source(
    row: Recording,
    annotation: Annotation,
    selected_indices: set[int],
) -> bool:
    if annotation.caption_type not in ("semantic", "cross_channel"):
        return True
    semantic_refs = [
        idx
        for idx in annotation.channel_idxs
        if idx < len(row.channel_names)
        and (row.channel_names[idx].startswith("sleep:") or row.channel_names[idx].startswith("workout:"))
    ]
    return not semantic_refs or bool(selected_indices.intersection(semantic_refs))


def _annotation_sort_key(annotation: Annotation) -> tuple[int, int, str]:
    type_order = {caption_type: pos for pos, caption_type in enumerate(PIPELINE_CARD_STAGE_ORDER)}
    start = annotation.window[0] if annotation.window else 10**9
    return (type_order.get(annotation.caption_type, 9), start, annotation.text)


def _draw_pipeline_signal_panel(
    ax: plt.Axes,
    row: Recording,
    selected_indices: list[int],
    annotations: list[Annotation],
) -> None:
    data = row.values
    time_axis = np.arange(data.shape[1])
    offsets = np.arange(len(selected_indices), dtype=float)[::-1] * 1.35
    index_to_y = {idx: offsets[pos] for pos, idx in enumerate(selected_indices)}
    frame_bottom = -0.75
    frame_top = offsets[0] + 0.78 if len(offsets) else 1.0

    ax.add_patch(
        Rectangle(
            (0, frame_bottom),
            data.shape[1],
            frame_top - frame_bottom,
            fill=False,
            linestyle=(0, (2, 2)),
            linewidth=1.5,
            edgecolor="#8a8a8a",
            zorder=0.5,
            clip_on=False,
        )
    )

    for pos, idx in enumerate(selected_indices):
        y_base = offsets[pos]
        values = np.asarray(data[idx], dtype=float)
        valid = np.isfinite(values)
        normalized = _scale_for_pipeline_plot(values, row.channel_names[idx])
        if _is_binary_semantic_channel(row.channel_names[idx], values):
            ax.step(time_axis[valid], normalized[valid] + y_base, where="post", color="#33413d", linewidth=1.9, zorder=3)
        else:
            ax.plot(time_axis[valid], normalized[valid] + y_base, color="#33413d", linewidth=1.7, zorder=3)
            _draw_statistical_summary_bar(ax, values, normalized, y_base)
        ax.hlines(y_base, 0, data.shape[1] - 1, color="#e5e7eb", linewidth=0.8, zorder=1)
        ax.text(
            -0.025 * data.shape[1],
            y_base,
            _short_channel_label(row.display_names[idx], row.channel_names[idx]),
            ha="right",
            va="center",
            fontsize=14.0,
            weight="bold",
            color="#4b5563",
        )

    for idx in selected_indices:
        channel_values = np.asarray(row.values[idx], dtype=float)
        is_binary_semantic = _is_binary_semantic_channel(row.channel_names[idx], channel_values)

        def _annotation_draw_priority(annotation: Annotation) -> int:
            if annotation.caption_type == "cross_channel":
                return 1
            if is_binary_semantic and annotation.caption_type == "semantic":
                return 2
            return 0

        channel_annotations = [
            annotation
            for annotation in annotations
            if annotation.window is not None and idx in annotation.channel_idxs
        ]
        if is_binary_semantic:
            channel_annotations = _merge_binary_overlap_annotations(channel_annotations)
        for annotation in sorted(channel_annotations, key=_annotation_draw_priority):
            _draw_annotation_highlight(ax, row, idx, index_to_y[idx], annotation)

    ax.set_xlim(0, data.shape[1])
    ax.set_ylim(frame_bottom, frame_top)
    ax.set_xlabel(_time_axis_label(data.shape[1]), fontsize=14)
    ax.set_yticks([])
    ax.text(
        0.0,
        1.025,
        "Time-series evidence",
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=19,
        weight="bold",
        clip_on=False,
    )
    ax.grid(axis="x", color="#e5e7eb", linewidth=0.8)
    for spine in ax.spines.values():
        spine.set_visible(False)


def _scale_for_pipeline_plot(values: np.ndarray, channel_name: str) -> np.ndarray:
    scaled = np.full_like(values, np.nan, dtype=float)
    valid = np.isfinite(values)
    if not valid.any():
        return scaled
    finite = values[valid]
    if _is_binary_semantic_channel(channel_name, values):
        active = finite > 0
        scaled[valid] = np.where(active, 0.48, 0.0)
        return scaled
    lo = float(np.nanmin(finite))
    hi = float(np.nanmax(finite))
    if hi - lo <= 1e-12:
        scaled[valid] = 0.0
    else:
        scaled[valid] = ((finite - lo) / (hi - lo)) * 0.82 - 0.41
    return scaled


def _is_binary_semantic_channel(channel_name: str, values: np.ndarray) -> bool:
    if not (channel_name.startswith("sleep:") or channel_name.startswith("workout:")):
        return False
    finite = values[np.isfinite(values)]
    if finite.size == 0:
        return True
    unique = np.unique(finite)
    return bool(np.all(np.isin(unique, [0.0, 1.0])))


def _draw_statistical_summary_bar(
    ax: plt.Axes,
    values: np.ndarray,
    normalized: np.ndarray,
    y_base: float,
) -> None:
    valid = np.isfinite(values) & np.isfinite(normalized)
    if not valid.any():
        return

    finite_values = values[valid]
    finite_normalized = normalized[valid] + y_base
    mean_value = float(np.nanmean(finite_values))
    std_value = float(np.nanstd(finite_values))
    min_y = float(np.nanmin(finite_normalized))
    max_y = float(np.nanmax(finite_normalized))
    mean_y = _interpolate_stat_position(mean_value, finite_values, finite_normalized)
    std_low_y = _interpolate_stat_position(mean_value - std_value, finite_values, finite_normalized)
    std_high_y = _interpolate_stat_position(mean_value + std_value, finite_values, finite_normalized)

    style = PIPELINE_STAGE_STYLES["statistical"]
    marker_color = style["marker"]
    x = -0.012 * len(values)
    width = max(4.0, 0.0065 * len(values))

    # Use Matplotlib's boxplot machinery as a compact side summary:
    # whiskers show min/max, the translucent box shows mean ± std,
    # and a manually drawn line marks the mean.
    stats = [
        {
            "med": mean_y,
            "q1": min(std_low_y, std_high_y),
            "q3": max(std_low_y, std_high_y),
            "whislo": min_y,
            "whishi": max_y,
            "fliers": [],
        }
    ]
    box = ax.bxp(
        stats,
        positions=[x],
        widths=[width],
        vert=True,
        patch_artist=True,
        showfliers=False,
        manage_ticks=False,
        boxprops={
            "facecolor": marker_color,
            "edgecolor": marker_color,
            "linewidth": 0.9,
            "alpha": 0.18,
            "zorder": 4.0,
        },
        whiskerprops={
            "color": marker_color,
            "linewidth": 1.1,
            "alpha": 0.55,
            "zorder": 4.1,
        },
        capprops={
            "color": marker_color,
            "linewidth": 1.2,
            "alpha": 0.65,
            "zorder": 4.2,
        },
        medianprops={
            "color": marker_color,
            "linewidth": 0.0,
            "alpha": 0.0,
            "zorder": 4.3,
        },
    )
    for artist_group in box.values():
        for artist in artist_group:
            artist.set_clip_on(False)

    ax.hlines(
        mean_y,
        x - width * 0.58,
        x + width * 0.58,
        colors=marker_color,
        linewidth=2.4,
        alpha=1.0,
        zorder=4.6,
        clip_on=False,
    )


def _interpolate_stat_position(value: float, values: np.ndarray, positions: np.ndarray) -> float:
    order = np.argsort(values)
    sorted_values = values[order]
    sorted_positions = positions[order]
    unique_values, unique_indices = np.unique(sorted_values, return_index=True)
    unique_positions = sorted_positions[unique_indices]
    if unique_values.size == 1:
        return float(unique_positions[0])
    clipped = float(np.clip(value, unique_values[0], unique_values[-1]))
    return float(np.interp(clipped, unique_values, unique_positions))


def _draw_annotation_highlight(
    ax: plt.Axes,
    row: Recording,
    idx: int,
    y_base: float,
    annotation: Annotation,
) -> None:
    style = PIPELINE_STAGE_STYLES.get(annotation.caption_type, PIPELINE_STAGE_STYLES["structural"])
    start, end = annotation.window or (None, None)
    if start is None or end is None:
        return
    is_binary_semantic = _is_binary_semantic_channel(
        row.channel_names[idx],
        np.asarray(row.values[idx], dtype=float),
    )

    if annotation.caption_type == "structural" and _is_spike_caption(annotation):
        values = np.asarray(row.values[idx], dtype=float)
        normalized = _scale_for_pipeline_plot(values, row.channel_names[idx])
        for minute in _spike_minutes(annotation):
            if 0 <= minute < len(values) and np.isfinite(normalized[minute]):
                ax.scatter(
                    [minute],
                    [normalized[minute] + y_base],
                    marker="^",
                    s=68,
                    color=style["fill"],
                    edgecolor=style["marker"],
                    linewidth=1.25,
                    zorder=5,
                )
        return

    if annotation.caption_type == "structural" and _is_trend_caption(annotation):
        _draw_structural_trend_arrow(ax, row, idx, y_base, annotation, style["fill"], style["fill"])
        return

    alpha = {"structural": 0.3, "semantic": 0.26, "cross_channel": 0.26, "statistical": 0.2}.get(annotation.caption_type, 0.08)
    facecolor = "#8ee6a8" if annotation.caption_type == "cross_channel" else style["color"]
    y_bottom = y_base - 0.52
    box_height = 1.04
    is_merged_overlap = annotation.label == "semantic_cross_channel_overlap"

    # Ensure consistent height/vertical alignment for semantic and cross-channel on binary signals
    if is_binary_semantic and annotation.caption_type in {"semantic", "cross_channel"}:
        y_bottom += 0.08
    ax.add_patch(
        Rectangle(
            (start, y_bottom),
            max(end - start, 1),
            box_height,
            facecolor=facecolor,
            edgecolor=style["marker"] if annotation.caption_type in {"semantic", "cross_channel"} else "none",
            linewidth=1.15 if annotation.caption_type in {"semantic", "cross_channel"} else 0,
            alpha=alpha,
            zorder=2,
        )
    )
    if is_merged_overlap:
        cross_style = PIPELINE_STAGE_STYLES["cross_channel"]
        ax.add_patch(
            Rectangle(
                (start, y_bottom),
                max(end - start, 1),
                box_height,
                facecolor="none",
                edgecolor=cross_style["marker"],
                linewidth=0,
                hatch="//",
                zorder=2.4,
            )
        )
    if annotation.caption_type in {"semantic", "cross_channel"}:
        end = max(end, start + 1)
        ax.vlines(
            [start, end],
            y_bottom,
            y_bottom + box_height,
            colors=style["marker"],
            linewidth=1.25,
            alpha=0.7 if annotation.caption_type == "semantic" else 0.85,
            zorder=3,
        )
        ax.hlines(
            y_bottom + box_height,
            start,
            end,
            colors=style["marker"],
            linewidth=1.45,
            alpha=0.62 if annotation.caption_type == "semantic" else 0.75,
            zorder=3,
        )
        ax.hlines(
            y_bottom,
            start,
            end,
            colors=style["marker"],
            linewidth=1.0,
            alpha=0.36 if annotation.caption_type == "semantic" else 0.45,
            zorder=3,
        )


def _merge_binary_overlap_annotations(annotations: list[Annotation]) -> list[Annotation]:
    semantic_by_window = {
        annotation.window: annotation
        for annotation in annotations
        if annotation.caption_type == "semantic" and annotation.window is not None
    }
    cross_by_window = {
        annotation.window: annotation
        for annotation in annotations
        if annotation.caption_type == "cross_channel" and annotation.window is not None
    }
    merged_windows = set(semantic_by_window).intersection(cross_by_window)
    merged_annotations = [
        Annotation(
            caption_type="semantic",
            text=semantic_by_window[window].text,
            channel_idxs=semantic_by_window[window].channel_idxs,
            window=window,
            label="semantic_cross_channel_overlap",
        )
        for window in merged_windows
    ]
    remaining_annotations = [
        annotation
        for annotation in annotations
        if annotation.window not in merged_windows or annotation.caption_type not in {"semantic", "cross_channel"}
    ]
    return remaining_annotations + merged_annotations


def _draw_structural_trend_arrow(
    ax: plt.Axes,
    row: Recording,
    idx: int,
    y_base: float,
    annotation: Annotation,
    arrow_color: str,
    bracket_color: str,
) -> None:
    start, end = annotation.window or (None, None)
    if start is None or end is None:
        return
    values = np.asarray(row.values[idx], dtype=float)
    normalized = _scale_for_pipeline_plot(values, row.channel_names[idx])
    lo = max(0, start)
    hi = min(len(values) - 1, max(end, start + 1))
    x = np.arange(lo, hi + 1)
    y = normalized[lo : hi + 1]
    valid = np.isfinite(y)
    if valid.sum() < 2:
        return

    x_valid = x[valid]
    y_valid = y[valid] + y_base
    slope, intercept = np.polyfit(x_valid, y_valid, 1)
    line_y = slope * x_valid + intercept
    ax.plot(x_valid, line_y, color=arrow_color, linewidth=2.1, alpha=0.88, zorder=4.2)

    arrow_start_x = float(x_valid[0])
    arrow_end_x = float(x_valid[-1])
    arrow_start_y = float(line_y[0])
    arrow_end_y = float(line_y[-1])
    ax.annotate(
        "",
        xy=(arrow_end_x, arrow_end_y),
        xytext=(arrow_start_x, arrow_start_y),
        arrowprops={
            "arrowstyle": "simple",
            "facecolor": arrow_color,
            "edgecolor": "blue",
            "linewidth": 1.2,
            "mutation_scale": 22,
            "alpha": 0.25,
            "shrinkA": 0,
            "shrinkB": 0,
        },
        zorder=4.6,
    )


def _draw_pipeline_caption_panel(ax: plt.Axes, annotations: list[Annotation]) -> None:
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    frame_left = 0.020
    frame_bottom = 0.000
    frame_width = 0.960
    frame_height = 1.000
    frame_top = frame_bottom + frame_height
    card_left = 0.060
    card_width = 0.880
    card_margin_y = 0.010

    ax.add_patch(
        Rectangle(
            (frame_left, frame_bottom),
            frame_width,
            frame_height,
            fill=False,
            linestyle=(0, (2, 2)),
            linewidth=1.5,
            edgecolor="#8a8a8a",
        )
    )
    ax.text(
        0.02,
        1.025,
        "Generated annotations",
        ha="left",
        va="top",
        fontsize=19.0,
        weight="bold",
        clip_on=False,
    )

    if not annotations:
        ax.text(0.08, 0.82, "No matching annotations for selected channels.", fontsize=11, color="#6b7280")
        return

    grouped = {caption_type: [ann for ann in annotations if ann.caption_type == caption_type] for caption_type in PIPELINE_CARD_STAGE_ORDER}
    wrapped_lines_by_type = {
        caption_type: _wrapped_stage_card_lines(caption_type, grouped[caption_type], max_lines=None)
        for caption_type in PIPELINE_CARD_STAGE_ORDER
    }
    min_heights = {
        "statistical": 0.150,
        "structural": 0.160,
        "semantic": 0.145,
        "cross_channel": 0.255,
    }
    text_start_offset = 0.055
    line_height = 0.026
    bottom_padding = 0.006
    gap = 0.008
    top = frame_top - card_margin_y
    bottom = frame_bottom + card_margin_y

    heights: dict[str, float] = {}
    for caption_type in PIPELINE_CARD_STAGE_ORDER:
        n_lines = max(1, len(wrapped_lines_by_type[caption_type]))
        content_height = text_start_offset + (n_lines * line_height) + bottom_padding
        heights[caption_type] = max(min_heights.get(caption_type, 0.12), content_height)

    total_height = sum(heights.values()) + gap * (len(PIPELINE_CARD_STAGE_ORDER) - 1)
    available = top - bottom
    if total_height > 1e-9:
        # Always scale to fill the full annotation panel height.
        scale = available / total_height
        for caption_type in PIPELINE_CARD_STAGE_ORDER:
            heights[caption_type] *= scale
        gap *= scale

    # Re-wrap after the final scaled card heights are known so the text uses
    # the available vertical space in each card instead of being truncated by a
    # fixed per-stage line cap.
    wrapped_lines_by_type = {}
    for caption_type in PIPELINE_CARD_STAGE_ORDER:
        max_lines = None
        if caption_type != "cross_channel":
            max_lines = max(
                1,
                int((heights[caption_type] - text_start_offset - bottom_padding) / line_height) + 2,
            )
        wrapped_lines_by_type[caption_type] = _wrapped_stage_card_lines(
            caption_type,
            grouped[caption_type],
            max_lines=max_lines,
        )

    y_cursor = top
    for caption_type in PIPELINE_CARD_STAGE_ORDER:
        height = heights[caption_type]
        y_bottom = y_cursor - height
        _draw_caption_stage_card(
            ax,
            caption_type,
            grouped[caption_type],
            y_bottom,
            height,
            wrapped_lines=wrapped_lines_by_type[caption_type],
            x_left=card_left,
            width=card_width,
        )
        y_cursor = y_bottom - gap


def _draw_caption_stage_card(
    ax: plt.Axes,
    caption_type: str,
    annotations: list[Annotation],
    y_bottom: float,
    height: float,
    *,
    wrapped_lines: list[str] | None = None,
    x_left: float = 0.060,
    width: float = 0.880,
) -> None:
    style = PIPELINE_STAGE_STYLES.get(caption_type, PIPELINE_STAGE_STYLES["structural"])
    card = FancyBboxPatch(
        (x_left, y_bottom),
        width,
        height,
        boxstyle="round,pad=0.006,rounding_size=0.018",
        linewidth=0,
        facecolor=style["fill"],
    )
    ax.add_patch(card)
    ax.add_patch(
        FancyBboxPatch(
            (x_left + 0.020, y_bottom + height - 0.042),
            0.30,
            0.026,
            boxstyle="round,pad=0.006,rounding_size=0.013",
            linewidth=0,
            facecolor=style["color"],
        )
    )
    ax.text(x_left + 0.042, y_bottom + height - 0.030, style["label"], fontsize=19.0, weight="bold", va="center", ha="left")
    if annotations:
        ax.text(x_left + width - 0.030, y_bottom + height - 0.030, f"{len(annotations)} captions", fontsize=16.4, va="center", ha="right", color="#4b5563")

    wrapped = wrapped_lines if wrapped_lines is not None else _wrapped_stage_card_lines(caption_type, annotations)
    rendered_text = "\n".join(wrapped)
    text_kwargs = {}
    text_fontsize = 18.6 if caption_type == "cross_channel" else 20.2
    text_linespacing = 0.98 if caption_type == "cross_channel" else 1.00
    text_artist = ax.text(
        x_left + 0.042,
        y_bottom + height - 0.062,
        rendered_text,
        fontsize=text_fontsize,
        va="top",
        ha="left",
        multialignment="left",
        color="#111827",
        linespacing=text_linespacing,
        **text_kwargs,
    )
    text_artist.set_clip_on(True)
    text_artist.set_clip_path(card)


def _stage_card_text(caption_type: str, annotations: list[Annotation]) -> str:
    if not annotations:
        return "No selected captions."
    if caption_type == "structural":
        spikes = [_format_card_caption(annotation) for annotation in annotations if _is_spike_caption(annotation)]
        trends = [_format_card_caption(annotation) for annotation in annotations if _is_trend_caption(annotation)]
        other = [
            _format_card_caption(annotation)
            for annotation in annotations
            if not _is_spike_caption(annotation) and not _is_trend_caption(annotation)
        ]
        parts: list[str] = []
        if spikes:
            parts.append("spikes: " + "; ".join(spikes))
        if trends:
            parts.append("trends: " + "; ".join(trends))
        if other:
            parts.append("other: " + "; ".join(other))
        return "\n".join(parts)
    if caption_type == "cross_channel":
        # Keep full captions but separate entries for readability.
        return "\n\n".join(f"- {_format_card_caption(annotation)}" for annotation in annotations)
    return "\n".join(f"- {_format_card_caption(annotation)}" for annotation in annotations)


def _format_card_caption(annotation: Annotation) -> str:
    text = " ".join(annotation.text.strip().rstrip(".").split())
    if annotation.window is None:
        return text
    start, end = annotation.window
    return f"{start}-{max(end - 1, start)}: {text}"




def _annotation_card_tag(annotation: Annotation) -> str | None:
    if annotation.caption_type == "statistical":
        return "key signal summaries"
    if annotation.label is None:
        return None
    return _pretty_label(str(annotation.label))


def _pretty_label(label: str) -> str:
    if label.startswith("workout:"):
        label = label.split(":", 1)[1]
    label = label.replace("HKWorkoutActivityType", "")
    label = label.replace("sleep_", "")
    label = label.replace("in_bed_not_sleeping", "in bed, not asleep")
    label = label.replace("_", " ")
    label = re.sub(r"(?<!^)(?=[A-Z])", " ", label)
    return " ".join(label.split()).strip().lower()


def _pretty_channel_or_label(channel_name: str, display_name: str) -> str:
    if channel_name.startswith("workout:") or channel_name.startswith("sleep:"):
        return _pretty_label(channel_name)
    return _short_channel_label(display_name, channel_name).lower()


def _wrap_caption_text(text: str, *, width: int) -> list[str]:
    lines: list[str] = []
    for paragraph in text.splitlines():
        wrapped = textwrap.wrap(paragraph, width=width)
        lines.extend(wrapped or [""])
    return lines


def _wrapped_stage_card_lines(
    caption_type: str,
    annotations: list[Annotation],
    *,
    max_lines: int | None = None,
) -> list[str]:
    text = _stage_card_text(caption_type, annotations)
    if caption_type == "cross_channel":
        wrapped = _wrap_cross_channel_text(text, width=48)
    else:
        wrapped = _wrap_caption_text(text, width=44)
    # Removed fixed max_lines_by_type; use max_lines argument instead.
    if max_lines is not None and len(wrapped) > max_lines:
        wrapped = wrapped[:max_lines]
        wrapped[-1] = wrapped[-1].rstrip(".") + "..."
    return wrapped


def _wrap_cross_channel_text(text: str, *, width: int) -> list[str]:
    lines: list[str] = []
    for paragraph in text.splitlines():
        if not paragraph.strip():
            lines.append("")
            continue
        if paragraph.startswith("- "):
            wrapped = textwrap.wrap(
                paragraph[2:],
                width=max(20, width - 2),
                initial_indent="- ",
                subsequent_indent="  ",
            )
        else:
            wrapped = textwrap.wrap(paragraph, width=width)
        lines.extend(wrapped or [""])
    return lines


def _estimate_caption_panel_extra_height(annotations: list[Annotation]) -> float:
    grouped = {caption_type: [ann for ann in annotations if ann.caption_type == caption_type] for caption_type in PIPELINE_CARD_STAGE_ORDER}
    min_heights = {
        "statistical": 0.150,
        "structural": 0.160,
        "semantic": 0.145,
        "cross_channel": 0.255,
    }
    text_start_offset = 0.055
    line_height = 0.026
    bottom_padding = 0.006
    gap = 0.008
    frame_bottom = 0.000
    frame_height = 1.000
    frame_top = frame_bottom + frame_height
    card_margin_y = 0.010
    top = frame_top - card_margin_y
    bottom = frame_bottom + card_margin_y
    available = top - bottom

    total_height = 0.0
    for caption_type in PIPELINE_CARD_STAGE_ORDER:
        lines = _wrapped_stage_card_lines(caption_type, grouped[caption_type], max_lines=None)
        n_lines = max(1, len(lines))
        content_height = text_start_offset + (n_lines * line_height) + bottom_padding
        total_height += max(min_heights.get(caption_type, 0.12), content_height)
    total_height += gap * (len(PIPELINE_CARD_STAGE_ORDER) - 1)

    overflow = max(0.0, total_height - available)
    # Convert normalized panel overflow into figure inches with a small buffer.
    return overflow * 11.0


def _is_spike_caption(annotation: Annotation) -> bool:
    text = annotation.text.lower()
    return any(keyword in text for keyword in ("spike", "peak", "outlier", "surge", "deviation", "anomaly", "jumped", "peaked"))


def _is_trend_caption(annotation: Annotation) -> bool:
    return _trend_direction(annotation) is not None


def _trend_direction(annotation: Annotation) -> str | None:
    text = annotation.text.lower()
    if any(keyword in text for keyword in ("increasing", "climbing", "upward", "rising")):
        return "increasing"
    if any(keyword in text for keyword in ("decreasing", "declining", "downward", "falling")):
        return "decreasing"
    return None


def _spike_minutes(annotation: Annotation) -> list[int]:
    explicit_time_matches = re.findall(
        r"\b(?:minute|minutes|hour|hours)\s+([0-9,\sand]+)",
        annotation.text,
        flags=re.IGNORECASE,
    )
    if explicit_time_matches:
        return [int(value) for match in explicit_time_matches for value in re.findall(r"\d+", match)]
    if annotation.window:
        start, end = annotation.window
        return [start] if start == end else [start, end]
    return []


def _short_channel_label(display_name: str, channel_name: str) -> str:
    if channel_name == "workout:HKWorkoutActivityTypeHighIntensityIntervalTraining":
        return "HIIT"
    if channel_name.startswith("workout:"):
        return display_name.title()
    if channel_name == "sleep:asleep":
        return "Asleep"
    if channel_name == "sleep:inbed":
        return "In bed"
    replacements = {
        "Apple Watch ": "",
        "iPhone ": "",
        "walking/running": "distance",
    }
    label = display_name
    for old, new in replacements.items():
        label = label.replace(old, new)
    return label[:28]


def _time_axis_label(n_steps: int) -> str:
    if n_steps == 1440:
        return "Minute of day"
    if n_steps == 24 * 7:
        return "Hour of week"
    return "Time step"


def plot_row(
    row: Recording,
    save_path: str | None = None,
    n_cols: int = 3,
) -> plt.Figure | None:
    channel_names = list(row.channel_names)
    n_channels = len(channel_names)
    data = row.values
    time_minutes = np.arange(data.shape[1])

    semantic_captions = [
        annotation.text for annotation in row.annotations if annotation.caption_type == "semantic" and annotation.text
    ]
    channel_captions: dict[str, dict[str, list[str]]] = {name: {} for name in channel_names}

    for caption in row.annotations:
        if not caption.text or caption.caption_type == "semantic":
            continue
        for idx in caption.channel_idxs:
            name = channel_names[idx]
            channel_captions[name].setdefault(caption.caption_type, []).append(caption.text)

    def _nan_regions(arr: np.ndarray, min_length: int = 30) -> list[tuple[int, int]]:
        regions = []
        in_region = False
        for i, val in enumerate(np.isnan(arr)):
            if val and not in_region:
                start = i
                in_region = True
            elif not val and in_region:
                if i - start >= min_length:
                    regions.append((start, i))
                in_region = False
        if in_region and len(arr) - start >= min_length:
            regions.append((start, len(arr)))
        return regions

    n_rows = ceil(n_channels / n_cols)
    fig, axes_2d = plt.subplots(n_rows, n_cols, figsize=(20, 4 * n_rows), sharex="col")
    axes = axes_2d.flatten()

    for i, (ax, name) in enumerate(zip(axes[:n_channels], channel_names)):
        valid = ~np.isnan(data[i])
        ax.plot(time_minutes[valid], data[i][valid], linewidth=0.8, color="steelblue")
        for t0, t1 in _nan_regions(data[i]):
            ax.axvspan(t0, t1, color="red", alpha=0.05)
        ax.set_ylabel(name, fontsize=6, rotation=90, ha="right", va="center")
        ax.tick_params(axis="y", labelsize=6)
        ax.tick_params(axis="x", labelsize=6, labelbottom=True)
        ax.set_xlim(0, data.shape[1])

    for col in range(n_cols):
        axes[col].set_xticks(range(0, data.shape[1] + 1, 200))

    for ax in axes[n_channels:]:
        ax.set_visible(False)

    bottom_row_indices = {
        (n_channels - 1 - col) // n_cols * n_cols + col
        for col in range(min(n_cols, n_channels))
    }

    for i in range(n_channels):
        ax = axes[i]
        caps = channel_captions.get(channel_names[i], {})
        parts = []
        for ann_type in ("statistical", "structural", "semantic"):
            if ann_type in caps:
                parts.append(textwrap.fill(" ".join(caps[ann_type]), width=80))
        if parts:
            caption_text = "\n".join("\n".join(parts).splitlines()[:10])
            ax.set_xlabel(caption_text, fontsize=6, labelpad=4)
        elif i in bottom_row_indices:
            ax.set_xlabel("Time (minutes)")

    fig.suptitle(f"{row.user_id}  |  {row.date}", fontsize=10, y=1.0)

    if semantic_captions:
        sem_text = textwrap.fill("  ".join(semantic_captions), width=140)
        n_lines = sem_text.count("\n") + 1
        line_height = (7 / 72) / fig.get_size_inches()[1]
        fig.text(0.5, 0.98, sem_text, ha="center", va="top", fontsize=7, style="italic")
        fig.tight_layout(rect=[0, 0, 1, 0.96 - line_height * max(n_lines - 1, 0)])
    else:
        fig.tight_layout(rect=[0, 0, 1, 0.96])

    if save_path:
        fig.savefig(save_path, dpi=150)
        plt.close(fig)
        return None
    else:
        plt.show()
    return fig


